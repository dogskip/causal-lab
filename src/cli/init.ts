import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { ContractError } from "../crdt.js";
import { BUILTIN_TARGETS } from "./catalog.js";

export type InitOptions = Readonly<{
  cwd: string;
  target: string;
  typescript: boolean;
  force: boolean;
}>;

export type InitResult = Readonly<{
  target: string;
  adapter: string;
  files: readonly string[];
}>;

function configSource(
  target: string,
  casePath: string,
  adapter: string,
): string {
  return `// Generated by crdt-fuzz init.
export default {
  target: ${JSON.stringify(target)},
  case: ${JSON.stringify("./" + casePath)},
  adapter: ${JSON.stringify("./" + adapter)},
};
`;
}

const ADAPTER_MJS = `// Generated by crdt-fuzz init. Replace this wrapper with your own adapter.
// Requires crdt-fuzz in this project: npm install -D crdt-fuzz
import { createBuiltinContext } from "crdt-fuzz/node";

export function createContext(definition) {
  return createBuiltinContext(definition);
}
`;

const ADAPTER_TS = `// Generated by crdt-fuzz init. Replace this wrapper with your own adapter.
// Requires crdt-fuzz in this project: npm install -D crdt-fuzz
import { createBuiltinContext } from "crdt-fuzz/node";
import type { VerificationCase } from "crdt-fuzz/node";

export function createContext(definition: VerificationCase) {
  return createBuiltinContext(definition);
}
`;

export function initProject(options: InitOptions): InitResult {
  const target = BUILTIN_TARGETS.find((item) => item.id === options.target);
  if (target === undefined)
    throw new ContractError("target must be yjs or or-map");
  const adapter = "adapters/example." + (options.typescript ? "ts" : "mjs");
  const casePath = "cases/" + target.id + ".json";
  const files = ["crdt-fuzz.config.mjs", adapter, casePath];
  const existing = files.filter((file) => existsSync(join(options.cwd, file)));
  if (existing.length > 0 && !options.force)
    throw new ContractError("refusing to overwrite: " + existing.join(", "));
  const example = readFileSync(
    new URL(
      "../../examples/verification/" + target.id + ".json",
      import.meta.url,
    ),
    "utf8",
  );
  const definition = JSON.parse(example) as unknown;
  for (const [file, content] of [
    [
      "crdt-fuzz.config.mjs",
      configSource(target.id, casePath, adapter),
    ],
    [adapter, options.typescript ? ADAPTER_TS : ADAPTER_MJS],
    [casePath, JSON.stringify(definition, null, 2) + "\n"],
  ] as const) {
    const path = join(options.cwd, file);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  return { target: target.id, adapter, files };
}
